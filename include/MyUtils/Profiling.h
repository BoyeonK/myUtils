#pragma once

// 비싼 계측 프로브를 켜고 끄는 공용 스위치.
//
// 계측은 비용에 따라 3단으로 나뉜다(ADR-0013).
//
//   1단  chunk·actor 수명 단위    항상 켜짐. 빈도가 낮아 사실상 공짜다
//   2단  배치·runnable 단위       항상 켜짐. 메시지당 1/32 이하
//   3단  메시지 단위 시계 읽기     이 스위치로 제어
//
// 3단만 여기에 걸린다. 1·2단은 스위치와 무관하게 항상 동작하므로,
// 재검토 조건 대부분은 이걸 켜지 않아도 관측할 수 있다.
//
// 컴파일 타임 매크로가 아니라 런타임 플래그인 이유는 ADR-0013 참고.
// 요약하면 꺼졌을 때 비용이 1ns 미만이라 매크로로 얻을 게 거의 없고,
// #ifdef 안의 코드는 컴파일되지 않으면 조용히 썩기 때문이다.

namespace MyUtils {

	// 기본값은 false. 프로브가 감싸는 것이 clock 호출이라 켜면 메시지당
	// 40~50ns가 추가된다.
	bool IsProfilingEnabled() noexcept;

	// 언제든 켜고 끌 수 있다. 켜기 전에 누적된 값은 그대로 남는다.
	void SetProfilingEnabled(bool enabled) noexcept;
}
